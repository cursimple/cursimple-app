  const languages = Object.freeze(['zh-CN', 'zh-TW', 'en']);
  const STORAGE_KEY = 'site-language';
  function normalizeLanguage(value) {
    if (typeof value !== 'string') return null;
    const language = value.trim().replace(/_/g, '-').toLowerCase();
    if (/^zh(?:-|$)/.test(language)) return /^zh-(?:hant|tw|hk|mo)(?:-|$)/.test(language) ? 'zh-TW' : 'zh-CN';
    if (/^en(?:-|$)/.test(language)) return 'en';
    return null;
  }
  function resolveLanguage({ query, saved } = {}) {
    return normalizeLanguage(query) || normalizeLanguage(saved) || 'zh-CN';
  }
  let current = 'zh-CN';
  let storage;
  if (typeof document !== 'undefined') {
    try { storage = localStorage; } catch { /* Storage can be unavailable in private mode. */ }
    let saved;
    try { saved = storage?.getItem(STORAGE_KEY); } catch { /* Use the URL choice or default. */ }
    current = resolveLanguage({
      query: new URL(location.href).searchParams.get('lang'), saved,
    });
  }
  function t(key, values = {}, language = current) {
    const template = messages[language]?.[key] ?? messages['zh-CN'][key];
    if (typeof template !== 'string') throw new Error(`Unknown translation key: ${key}`);
    return template.replace(/\{(\w+)\}/g, (match, name) => values[name] == null ? match : String(values[name]));
  }
  function apply() {
    document.documentElement.lang = current;
    document.querySelectorAll('[data-i18n]').forEach((element) => { element.textContent = t(element.dataset.i18n); });
    for (const attribute of ['alt', 'aria-label', 'content']) {
      document.querySelectorAll(`[data-i18n-${attribute}]`).forEach((element) => {
        element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
      });
    }
    document.querySelector('meta[property="og:locale"]')?.setAttribute('content', { 'zh-CN': 'zh_CN', 'zh-TW': 'zh_TW', en: 'en_US' }[current]);
    document.querySelectorAll('#siteLanguage').forEach((select) => { select.value = current; });
  }
  function setLanguage(value) {
    const language = normalizeLanguage(value);
    if (!language) return false;
    current = language;
    try { storage?.setItem(STORAGE_KEY, current); } catch { /* Selection still works without storage. */ }
    // The URL carries an explicit choice when sharing, retaining the section / modal hash.
    const url = new URL(location.href);
    url.searchParams.set('lang', current);
    history.replaceState(history.state, '', url);
    apply();
    document.dispatchEvent(new CustomEvent('site-language-change', { detail: { language: current } }));
    return true;
  }
  function init() {
    apply();
    document.querySelector('#siteLanguage')?.addEventListener('change', (event) => setLanguage(event.target.value));
  }
  const formatDate = (date, language = current) => new Intl.DateTimeFormat(language, { year: 'numeric', month: 'long', day: 'numeric' }).format(date);
  return { messages, languages, normalizeLanguage, resolveLanguage, t, formatDate, init, apply, setLanguage, get language() { return current; } };
